            сумма = (цена * кол).quantize(Decimal('0.01'))
            Состав_производства.objects.create(
                Заказы_на_производство=заказы_произв[зп_idx],
                Материал_УИД=материалы[мат_idx],
                Продукция_УИД=продукция[прод_idx],
                Тип_записи=тип_зап,
                Количество=кол,
                Цена=цена,
                Сумма=сумма,
            )

